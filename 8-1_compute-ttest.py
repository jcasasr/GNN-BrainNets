import numpy as np
import pandas as pd
from scipy.stats import chisquare, ttest_ind


# Perform chi-square test
def perform_ttest(dataset1, dataset2):
    """
    Perform a t-test between two datasets, to see if they come from the same distribution.

    Parameters:
    dataset1 (list or array-like): First dataset.
    dataset2 (list or array-like): Second dataset.

    Returns:
    tuple: t-statistic and p-value of the t-test.
    """
    result = ttest_ind(dataset1, dataset2, axis=0)

    print(f"T-Statistic: {result.statistic}")
    print(f"P-value: {result.pvalue}")

    if result.pvalue < 0.05:
        print("H0 is true. The distributions are likely DIFFERENT.")
    else:
        print("Cannot discard H0. The distributions are likely SIMILAR.")

    return result.statistic, result.pvalue

